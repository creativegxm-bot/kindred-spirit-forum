// IQ estimation based on score (rough mapping)
export const estimateIQ = (score: number, totalQuestions: number): number => {
  const percentage = score / totalQuestions;
  if (percentage >= 0.95) return 145;
  if (percentage >= 0.90) return 138;
  if (percentage >= 0.85) return 132;
  if (percentage >= 0.80) return 126;
  if (percentage >= 0.75) return 120;
  if (percentage >= 0.70) return 115;
  if (percentage >= 0.65) return 112;
  if (percentage >= 0.60) return 108;
  if (percentage >= 0.55) return 105;
  if (percentage >= 0.50) return 100;
  if (percentage >= 0.45) return 97;
  if (percentage >= 0.40) return 93;
  if (percentage >= 0.35) return 90;
  if (percentage >= 0.30) return 86;
  if (percentage >= 0.25) return 82;
  if (percentage >= 0.20) return 78;
  return 74;
};

